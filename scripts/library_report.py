"""Generate the model-catalogue report (tests/numerical/LIBRARY.md).

For every library model (and the core starter set) it runs the noiseless recovery check
(`curvestudio.testing.model_recovery`): a multistart fit of the model's own example curve,
and for information a single start from ``initial_guess``. The report lists model counts per
category and per family, the share of models recovered by a single start and by multistart,
the worst relative parameter error, and one row per model.

A model that fails the recovery check is listed with its failure message and makes the exit
status 1. The output has no timestamp, so regenerating it changes the file only when the
catalogue or the numerical results change.

Usage: ``uv run python scripts/library_report.py [--output PATH]``
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from curvestudio.models import ModelSpec
from curvestudio.models.starter import STARTER_MODELS
from curvestudio.testing.model_recovery import RecoveryReport, check_model_recovery
from curvestudio_engineering import catalogue as engineering_catalogue
from curvestudio_models import catalogue
from curvestudio_models.generated import ids as generated_ids
from curvestudio_models.register import family_of

_REPO_ROOT = Path(__file__).resolve().parents[1]
_DEFAULT_OUTPUT = _REPO_ROOT / "tests" / "numerical" / "LIBRARY.md"
_CORE_FAMILY = "core starter set"
_ENGINEERING_FAMILY = "engineering"


@dataclass(frozen=True)
class Row:
    """One model's recovery outcome; ``report`` is ``None`` when the check failed."""

    spec: ModelSpec
    family: str
    report: RecoveryReport | None
    failure: str


def measure(spec: ModelSpec, family: str) -> Row:
    try:
        return Row(spec, family, check_model_recovery(spec), "")
    except AssertionError as exc:
        return Row(spec, family, None, str(exc))


def _percent(count: int, total: int) -> str:
    return "n/a" if total == 0 else f"{100.0 * count / total:.1f} % ({count}/{total})"


def _counts_table(title: str, counts: Counter[str]) -> list[str]:
    lines = [f"## {title}", "", "| Name | Models |", "|---|---:|"]
    lines += [f"| {name} | {count} |" for name, count in sorted(counts.items())]
    return [*lines, ""]


def _count(rows: list[Row], family: str) -> int:
    return sum(r.family == family for r in rows)


def render(rows: list[Row]) -> str:
    ok = [r for r in rows if r.report is not None]
    reports = [r.report for r in ok if r.report is not None]
    single_converged = sum(rep.single_start_converged for rep in reports)
    single_recovered = sum(rep.single_start_recovered for rep in reports)
    worst = max(ok, key=lambda r: r.report.max_relative_error if r.report else 0.0, default=None)
    worst_cond = max(
        ok, key=lambda r: r.report.jacobian_condition if r.report else 0.0, default=None
    )
    failures = [r for r in rows if r.report is None]

    lines = [
        "# Model catalogue report",
        "",
        "Generated by `scripts/library_report.py`; do not edit by hand.",
        "",
        "## Summary",
        "",
        f"- Models: {len(rows)} ({_count(rows, _CORE_FAMILY)} in the core starter set, "
        f"{len(rows) - _count(rows, _CORE_FAMILY) - _count(rows, _ENGINEERING_FAMILY)} in the "
        f"library, {_count(rows, _ENGINEERING_FAMILY)} engineering)",
        f"- Hand-written models (library and core starter set): "
        f"{len(rows) - _count(rows, _ENGINEERING_FAMILY)}",
        f"- Engineering models: {_count(rows, _ENGINEERING_FAMILY)}",
        f"- Generated model ids: {len(generated_ids())} by default, "
        f"{len(generated_ids(exhaustive=True))} with the long tail (exhaustive); their recovery "
        "is checked by `tests/unit/library/test_generated_recovery.py`",
        f"- Recovered by multistart (12 starts, tolerance 1e-6): {_percent(len(ok), len(rows))}",
        f"- Single start converged: {_percent(single_converged, len(ok))}",
        f"- Single start recovered the parameters (tolerance 1e-4): "
        f"{_percent(single_recovered, len(ok))}",
    ]
    if worst is not None and worst.report is not None:
        lines.append(
            f"- Worst recovery error: {worst.report.max_relative_error:.3g} ({worst.spec.id})"
        )
    if worst_cond is not None and worst_cond.report is not None:
        lines.append(
            f"- Worst Jacobian condition number: {worst_cond.report.jacobian_condition:.3g} "
            f"({worst_cond.spec.id})"
        )
    lines.append(f"- Failing models: {len(failures)}")
    lines.append("")
    lines += _counts_table("Models per category", Counter(r.spec.category for r in rows))
    lines += _counts_table("Models per family", Counter(r.family for r in rows))
    lines += [
        "## Models",
        "",
        "| Id | k | Category | Family | Single start converged | Single start recovered |",
        "|---|---:|---|---|:-:|:-:|",
    ]
    for r in sorted(rows, key=lambda row: (row.spec.category, row.spec.id)):
        rep = r.report
        converged = "n/a" if rep is None else ("yes" if rep.single_start_converged else "no")
        recovered = "n/a" if rep is None else ("yes" if rep.single_start_recovered else "no")
        lines.append(
            f"| `{r.spec.id}` | {len(r.spec.parameters)} | {r.spec.category} | {r.family} | "
            f"{converged} | {recovered} |"
        )
    if failures:
        lines += ["", "## Failures", ""]
        lines += [f"- `{r.spec.id}`: {r.failure}" for r in failures]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    parser.add_argument("--output", type=Path, default=_DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    rows = [measure(spec, family_of(spec.id)) for spec in catalogue()]
    rows += [measure(spec, _CORE_FAMILY) for spec in STARTER_MODELS]
    rows += [measure(spec, _ENGINEERING_FAMILY) for spec in engineering_catalogue()]
    text = render(rows)
    args.output.write_text(text, encoding="utf-8")
    failures = [r.spec.id for r in rows if r.report is None]
    print(f"wrote {args.output} ({len(rows)} models, {len(failures)} failing)")
    if failures:
        print("failing models: " + ", ".join(failures), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
